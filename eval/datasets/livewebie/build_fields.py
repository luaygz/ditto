"""Translate the LiveWeb-IE queries into one prompted-mode ``fields.yaml`` per website.

Mechanical, so the field definitions carry no knowledge from looking at pages or labels:

* fields come from :func:`ditto.evaluation.datasets.livewebie.site_fields` (one per attribute and
  cardinality; type_1/type_2 -> ``scalar``, type_3/type_4 -> ``list``; a list-valued homonym of a
  scalar attribute becomes ``<attribute>_list``);
* the description is the dataset's own single-attribute query text for that field (up to two),
  else the attribute name plus the first multi-attribute query that asks for it, plus the value
  convention for image (``@src``) and link (``@href``) attributes, which follows the paper's
  annotation protocol (Appendix C);
* image and link fields get ``type_check: url``; no examples (they would leak ground truth).

Usage::

    uv run python eval/datasets/livewebie/build_fields.py [--release data/livewebie/release/LiveWeb_IE]
"""

from __future__ import annotations

import argparse
import textwrap
from collections.abc import Iterable
from pathlib import Path
from typing import Any

import yaml

from ditto.evaluation.datasets.livewebie import (
    CITATION,
    LICENSE_TERMS,
    RELEASE_COMMIT,
    RELEASE_REPO,
    FieldDef,
    load_release,
    site_fields,
)

HERE = Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
FIELDS_DIR = HERE / "fields"
DEFAULT_RELEASE = REPO_ROOT / "data" / "livewebie" / "release" / "LiveWeb_IE"


def field_entry(fd: FieldDef) -> dict[str, Any]:
    entry: dict[str, Any] = {"description": fd.description(), "type": fd.kind}
    if fd.category in ("image", "link"):
        entry["type_check"] = "url"
    return entry


def render(website: str, fields: list[FieldDef]) -> str:
    header = [
        f"Prompted-mode fields for {website} from LiveWeb-IE ({RELEASE_REPO}@{RELEASE_COMMIT[:12]}),",
        "generated by eval/datasets/livewebie/build_fields.py from the dataset's queries.",
        "Groups per field: " + "; ".join(f"{fd.name}: {','.join(fd.groups)}" for fd in fields),
        f"Derived from the LiveWeb-IE dataset. License: {LICENSE_TERMS}",
        f"Cite: {CITATION}",
    ]
    lines: list[str] = []
    for para in header:
        lines.extend(textwrap.wrap(para, width=97) or [""])
    body = yaml.safe_dump(
        {"fields": {fd.name: field_entry(fd) for fd in fields}},
        sort_keys=False,
        allow_unicode=True,
        width=100,
    )
    return "".join(f"# {line}\n" for line in lines) + body


def build(release_root: Path, out_dir: Path) -> list[Path]:
    release = load_release(release_root)
    out_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for website in release.websites():
        path = out_dir / f"{website}.yaml"
        path.write_text(render(website, site_fields(release, website)), encoding="utf-8")
        written.append(path)
    return written


def main(argv: Iterable[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--release", type=Path, default=DEFAULT_RELEASE)
    ap.add_argument("--out", type=Path, default=FIELDS_DIR)
    args = ap.parse_args(list(argv) if argv is not None else None)
    for path in build(args.release, args.out):
        print(path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
